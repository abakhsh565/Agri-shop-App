type Lang = keyof typeof translations;
type Keys = keyof typeof translations["en"];

/**
 * The dictionary's own key set, exported so generated key families can be typed
 * against it.
 */
export type I18nKey = Keys;

/**
 * `key` stays `string` deliberately, and this is the reasoned choice rather than an
 * oversight. Narrowing it to `Keys` was tried: tsc reported 26 call sites that compute
 * their key (`t(`area.${id}`)`, `t("signal." + code)`, and `t` itself passed as a
 * `(key: string) => string` callback into the reminder and permission helpers). Those
 * are legitimate generated-key families, and narrowing only forces a cast at each one —
 * which hides the check rather than adding it.
 *
 * A missing or misspelled key is therefore caught by the guards instead, and both fail
 * the build with a baseline of zero:
 *   - `tests/unit/i18nCoverage.test.ts` — every literal key passed to the translator exists in both
 *     dictionaries, and no shipped JSX may hardcode user-facing English.
 *   - `tests/unit/i18nParity.test.ts` — the EN and UR maps carry exactly the same keys,
 *     with identical placeholders.
 * Generated families are additionally typed against `I18nKey` at their source, so a
 * key that cannot exist is caught where it is built rather than where it is used.
 */
export type TranslateFn = (key: string, fallbackOrParams?: string | Record<string, string | number>) => string;

function translate(lang: Lang, key: string, fallbackOrParams?: string | Record<string, string>): string {
    const dict = translations[lang] ?? translations.en;
    let text = (dict as Record<string, string>)[key as Keys] ?? (translations.en as Record<string, string>)[key as Keys] ?? (typeof fallbackOrParams === 'string' ? fallbackOrParams : undefined) ?? key;
    if (typeof fallbackOrParams === 'object' && fallbackOrParams !== null) {
      for (const [k, v] of Object.entries(fallbackOrParams)) {
        text = text.replace(new RegExp('\{' + k + '\}', 'g'), String(v));
      }
    }
  return text;
}

export function useT() {
  const { language } = useThemeStore();
  return ((key: string, fallbackOrParams?: string | Record<string, string>) =>
    translate(language as Lang, key, fallbackOrParams)) as TranslateFn;
}

/**
 * Translate outside React — for the plumbing that turns a database failure into
 * words (lib/db.ts friendly()), which is not a component and cannot use a hook.
 * It reads the same store the UI reads, so a failure is reported in the language
 * the person is actually looking at instead of always English.
 */
export function tNow(key: string, fallbackOrParams?: string | Record<string, string>): string {
  return translate(useThemeStore.getState().language as Lang, key, fallbackOrParams);
}
