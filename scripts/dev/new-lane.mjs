#!/usr/bin/env node
/**
 * new-lane.mjs — scaffold a new browser lane with the standard harness already
 * wired, so the recurring harness mistakes (wrong storage key, one-shot
 * visibility snapshot, sign-in invented instead of reused) stop being possible
 * to make from scratch.
 *
 * The scaffold is deliberately small: console capture on, a real navigation,
 * and a pointer to tests/e2e/helpers.ts for sign-in and fixtures. The lane is
 * registered in scripts/dev/lane-map.json with the safe default coverage so it
 * can never be silently skipped — narrow the globs once you know what it covers.
 *
 * Usage: node scripts/dev/new-lane.mjs <lane-name>
 */
import fs from 'node:fs';
import path from 'node:path';

const name = process.argv[2];
if (!name || !/^[a-zA-Z][a-zA-Z0-9]*$/.test(name)) {
  console.error('usage: node scripts/dev/new-lane.mjs <lane-name>   (camelCase, no extension)');
  process.exit(2);
}

const specPath = path.join('tests/e2e', `${name}.spec.ts`);
if (fs.existsSync(specPath)) {
  console.error(`refusing to overwrite an existing lane: ${specPath}`);
  process.exit(2);
}

const spec = `import { test, expect } from '@playwright/test';

/**
 * ${name} lane.
 *
 * Sign-in, fixture lookup and QA helpers live in ./helpers.ts — reuse them
 * rather than inventing a session. A lane may only report PASS from behaviour
 * it actually exercised.
 *
 * Generated by scripts/dev/new-lane.mjs. Coverage is registered in
 * scripts/dev/lane-map.json (default = src/**, safe but broad) — narrow it to
 * the files this spec really depends on so tier selection and lane caching stay
 * honest.
 */
test.describe('${name}', () => {
  test('TODO: name the behaviour this lane proves', async ({ page }) => {
    const consoleErrors: string[] = [];
    page.on('console', (m) => { if (m.type() === 'error') consoleErrors.push(m.text()); });

    await page.goto('/');
    await expect(page.locator('body')).toBeVisible();

    // Known pre-existing document warnings are excluded by name — never by silencing
    // every error.
    expect(consoleErrors.filter((e) => !/X-Frame-Options|favicon/i.test(e))).toEqual([]);
  });
});
`;

fs.writeFileSync(specPath, spec);

const mapPath = 'scripts/dev/lane-map.json';
const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
if (!(name in map.lanes)) {
  map.lanes[name] = ['src/**'];
  fs.writeFileSync(mapPath, `${JSON.stringify(map, null, 2)}\n`);
  console.log(`registered ${name} in ${mapPath} with the safe default coverage ["src/**"] — narrow it.`);
}

console.log(`created ${specPath}`);
console.log('next: name the behaviour, reuse tests/e2e/helpers.ts for sign-in, then run');
console.log(`  npx playwright test tests/e2e/${name}.spec.ts --workers=1`);
